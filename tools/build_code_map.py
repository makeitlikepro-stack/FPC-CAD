#!/usr/bin/env python3
"""Build docs/CODE_MAP.md: a compact index of Pascal units for low-token navigation.

For each .pas unit under the given roots it records the unit name, its path and
line count, the interface `uses` list, and the public type/routine declarations
found in the interface section. Bodies are never included.

Usage: python3 tools/build_code_map.py [--root DIR ...] [--out FILE]
Run from the repository root. Pure stdlib, no network, deterministic output.
"""
import argparse
import os
import re
import sys

UNIT_RE = re.compile(r"^\s*unit\s+([\w.]+)\s*;", re.IGNORECASE | re.MULTILINE)
INTF_RE = re.compile(r"^\s*interface\b", re.IGNORECASE | re.MULTILINE)
IMPL_RE = re.compile(r"^\s*implementation\b", re.IGNORECASE | re.MULTILINE)
USES_RE = re.compile(r"\buses\b(.*?);", re.IGNORECASE | re.DOTALL)
DECL_RE = re.compile(
    r"^\s*(T\w+\s*=\s*(?:class|record|object|interface)\b[^\n]*"
    r"|(?:procedure|function|constructor|destructor)\s+\w+[^\n;]*"
    r")",
    re.IGNORECASE | re.MULTILINE,
)


def strip_comments(text):
    text = re.sub(r"\{.*?\}", "", text, flags=re.DOTALL)
    text = re.sub(r"\(\*.*?\*\)", "", text, flags=re.DOTALL)
    text = re.sub(r"//[^\n]*", "", text)
    return text


def parse_unit(path):
    with open(path, encoding="utf-8", errors="replace") as fh:
        raw = fh.read()
    lines = raw.count("\n") + 1
    text = strip_comments(raw)
    unit = UNIT_RE.search(text)
    if not unit:
        return None
    intf = INTF_RE.search(text)
    impl = IMPL_RE.search(text)
    start = intf.end() if intf else 0
    end = impl.start() if impl else len(text)
    section = text[start:end]
    uses = []
    um = USES_RE.search(section)
    if um:
        uses = [u.strip() for u in um.group(1).split(",") if u.strip()]
    decls = []
    for m in DECL_RE.finditer(section):
        decl = " ".join(m.group(1).split())
        decls.append(decl[:120])
    return {
        "unit": unit.group(1),
        "path": path,
        "lines": lines,
        "uses": uses,
        "decls": decls,
    }


def collect(roots):
    units = []
    for root in roots:
        for dirpath, dirnames, filenames in os.walk(root):
            dirnames[:] = sorted(d for d in dirnames if not d.startswith("."))
            for name in sorted(filenames):
                if name.lower().endswith(".pas"):
                    info = parse_unit(os.path.join(dirpath, name))
                    if info:
                        units.append(info)
    return sorted(units, key=lambda u: u["path"])


def render(units):
    out = [
        "# CODE MAP",
        "",
        "Generated by `tools/build_code_map.py`. Do not edit by hand.",
        "Read this map first; open only the unit files you need.",
        "",
        f"Units: {len(units)}",
        "",
    ]
    for u in units:
        out.append(f"## {u['unit']}  `{u['path']}` ({u['lines']} lines)")
        if u["uses"]:
            out.append("- uses: " + ", ".join(u["uses"]))
        for d in u["decls"]:
            out.append(f"- {d}")
        out.append("")
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", action="append", default=None)
    ap.add_argument("--out", default="docs/CODE_MAP.md")
    args = ap.parse_args()
    roots = args.root or ["src"]
    units = collect(roots)
    os.makedirs(os.path.dirname(args.out) or ".", exist_ok=True)
    with open(args.out, "w", encoding="utf-8") as fh:
        fh.write(render(units))
    print(f"wrote {args.out}: {len(units)} units", file=sys.stderr)


if __name__ == "__main__":
    main()
