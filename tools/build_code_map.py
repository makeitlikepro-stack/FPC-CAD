#!/usr/bin/env python3
"""Build docs/CODE_MAP.md: a compact, grep-friendly index of Pascal units.

One line per unit: path, unit name, line count, class names and routine names
from the interface section. Signatures, `uses` lists and bodies are omitted to
keep the map small. Use `grep -n "ClassName" docs/CODE_MAP.md` to locate code.

Usage: python3 tools/build_code_map.py [--root DIR ...] [--out FILE]
Run from the repository root. Pure stdlib, no network, deterministic output.
"""
import argparse
import os
import re
import sys

UNIT_RE = re.compile(r"^\s*unit\s+([\w.]+)\s*;", re.IGNORECASE | re.MULTILINE)
INTF_RE = re.compile(r"^\s*interface\b", re.IGNORECASE | re.MULTILINE)
IMPL_RE = re.compile(r"^\s*implementation\b", re.IGNORECASE | re.MULTILINE)
CLASS_RE = re.compile(r"^\s*(T\w+)\s*=\s*(?:class|record|object|interface)\b", re.IGNORECASE | re.MULTILINE)
ROUTINE_RE = re.compile(r"^\s*(?:procedure|function|constructor|destructor)\s+(\w+(?:\.\w+)?)", re.IGNORECASE | re.MULTILINE)


def strip_comments(text):
    text = re.sub(r"\{.*?\}", "", text, flags=re.DOTALL)
    text = re.sub(r"\(\*.*?\*\)", "", text, flags=re.DOTALL)
    text = re.sub(r"//[^\n]*", "", text)
    return text


def unique(names):
    seen = []
    for n in names:
        if n not in seen:
            seen.append(n)
    return seen


def parse_unit(path):
    with open(path, encoding="utf-8", errors="replace") as fh:
        raw = fh.read()
    lines = raw.count("\n") + 1
    text = strip_comments(raw)
    unit = UNIT_RE.search(text)
    if not unit:
        return None
    intf = INTF_RE.search(text)
    impl = IMPL_RE.search(text)
    start = intf.end() if intf else 0
    end = impl.start() if impl else len(text)
    section = text[start:end]
    return {
        "unit": unit.group(1),
        "path": path,
        "lines": lines,
        "classes": unique(m.group(1) for m in CLASS_RE.finditer(section)),
        "routines": unique(m.group(1) for m in ROUTINE_RE.finditer(section)),
    }


def collect(roots):
    units = []
    for root in roots:
        for dirpath, dirnames, filenames in os.walk(root):
            dirnames[:] = sorted(d for d in dirnames if not d.startswith("."))
            for name in sorted(filenames):
                if name.lower().endswith(".pas"):
                    info = parse_unit(os.path.join(dirpath, name))
                    if info:
                        units.append(info)
    return sorted(units, key=lambda u: u["path"])


def render(units, with_routines=False):
    out = [
        "# CODE MAP",
        "",
        "Generated by `tools/build_code_map.py`. Do not edit by hand.",
        "Format: `path` | unit | lines | C: classes [| R: routines with --routines]",
        "",
    ]
    for u in units:
        parts = [f"`{u['path']}` | {u['unit']} | {u['lines']}"]
        if u["classes"]:
            parts.append("C: " + " ".join(u["classes"]))
        if with_routines and u["routines"]:
            parts.append("R: " + " ".join(u["routines"]))
        out.append(" | ".join(parts))
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", action="append", default=None)
    ap.add_argument("--out", default="docs/CODE_MAP.md")
    ap.add_argument("--routines", action="store_true", help="also list routine names (bigger map)")
    args = ap.parse_args()
    roots = args.root or ["src"]
    units = collect(roots)
    os.makedirs(os.path.dirname(args.out) or ".", exist_ok=True)
    with open(args.out, "w", encoding="utf-8") as fh:
        fh.write(render(units, with_routines=args.routines))
    print(f"wrote {args.out}: {len(units)} units", file=sys.stderr)


if __name__ == "__main__":
    main()
