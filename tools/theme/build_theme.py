#!/usr/bin/env python3
"""FPC-CAD light style sheet: the FPC Visual IDE theme template
(ide.css.tpl, copied from FPC-Visual-IDE assets/theme) plus cad.css.tpl,
coloured with the IDE's Light palette (Light.fvtheme), written to
assets/styles/cad-light.css. Roles: {{role}} = #RRGGBB, {{role:AA}} = with alpha.

    python3 tools/theme/build_theme.py
"""
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE.parents[1] / "assets" / "styles" / "cad-light.css"


def palette() -> dict:
    roles, section = {}, ""
    for line in (HERE / "Light.fvtheme").read_text().splitlines():
        line = line.strip()
        if line.startswith("["):
            section = line
        elif section == "[palette]" and "=" in line and not line.startswith(";"):
            k, v = (x.strip() for x in line.split("=", 1))
            roles[k] = v
    return roles


def render(text: str, roles: dict) -> str:
    def sub(m):
        name, alpha = m.group(1), m.group(2)
        if name not in roles:
            raise SystemExit(f"unknown colour role {name}")
        return roles[name][:7] + (alpha or "")
    return re.sub(r"\{\{([a-z-]+)(?::([0-9A-Fa-f]{2}))?\}\}", sub, text)


def main() -> None:
    roles = palette()
    text = (HERE / "ide.css.tpl").read_text() + "\n" + (HERE / "cad.css.tpl").read_text()
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("// Generated by tools/theme/build_theme.py - do not edit.\n" + render(text, roles))
    print(f"{OUT} ({len(roles)} colour roles)")


if __name__ == "__main__":
    main()
